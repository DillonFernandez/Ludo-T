package com.ludot.model;

// Names the destination choices used by mystery-cell effects.
public enum MysteryEffect {

    // Sends the piece to the Alpha location.
    ALPHA,

    // Sends the piece to the Beta location.
    BETA,

    // Sends the piece to the Gamma location.
    GAMMA,

    // Sends the piece back to its home base.
    BASE,

    // Sends the piece to its starting square.
    STARTING_SQUARE,

    // Sends the piece to its approach square.
    APPROACH
}